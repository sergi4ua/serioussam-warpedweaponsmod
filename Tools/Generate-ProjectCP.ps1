<#
  Regenerates Sources\ClassicsPatch\EntitiesTSE\EntitiesCP.vcxproj (+ .filters): the Warped
  Weapons build of the Serious Sam Classics Patch 1.9.4 entities (Bin\Entities_Custom.dll).

  The sources in Sources\ClassicsPatch are the patch's CustomMod\EntitiesTSE and
  CustomMod\CommonEntities (tag 1.9.4, ThirdParty\ClassicsPatch) with the Warped Weapons
  changes applied; every change is marked with "[WW]". Core, API and XGizmo headers come
  from ThirdParty\ClassicsPatch. The DLL links against the released ClassicsCore.dll through
  an import library built from Sources\ClassicsPatch\ClassicsCore.def.

  Run it after adding or removing an entity source (*.es).
#>
param()

$ErrorActionPreference = 'Stop'
$root    = Split-Path -Parent $PSScriptRoot
$projDir = Join-Path $root 'Sources\ClassicsPatch\EntitiesTSE'

# entity sources the Classics Patch does not compile for TSE 1.07
$excluded = @('Weapons\GhostBusterRay.es', 'Weapons\Pipebomb.es', 'Weapons\Water.es')
$esFiles  = Get-ChildItem $projDir -Recurse -Filter *.es | ForEach-Object { $_.FullName.Substring($projDir.Length + 1) } |
            Where-Object { $excluded -notcontains $_ } | Sort-Object
$handCpp  = @('Common\Common.cpp', 'Common\HUD.cpp', 'Common\PathFinding.cpp',
              '..\CommonEntities\Common\EmanatingParticles.cpp', '..\CommonEntities\Common\Particles.cpp')

$sb = New-Object System.Text.StringBuilder
function W([string]$s) { [void]$sb.AppendLine($s) }

W '<?xml version="1.0" encoding="utf-8"?>'
W '<!-- Generated by Tools\Generate-ProjectCP.ps1 - do not edit by hand. -->'
W '<Project DefaultTargets="Build" ToolsVersion="Current" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
W '  <ItemGroup Label="ProjectConfigurations">'
foreach ($cfg in 'Debug','Release') {
  W "    <ProjectConfiguration Include=`"$cfg|Win32`"><Configuration>$cfg</Configuration><Platform>Win32</Platform></ProjectConfiguration>"
}
W '  </ItemGroup>'
W '  <PropertyGroup Label="Globals">'
W '    <ProjectGuid>{0C7D3E2A-5B6F-4E8A-9D21-7F3A4B5C6D7E}</ProjectGuid>'
W '    <RootNamespace>EntitiesCP</RootNamespace>'
W '    <ProjectName>EntitiesCP</ProjectName>'
W '  </PropertyGroup>'
W '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.Default.props" />'
W '  <PropertyGroup Label="Configuration">'
W '    <ConfigurationType>DynamicLibrary</ConfigurationType>'
W '    <PlatformToolset Condition="''$(PlatformToolset)''==''''">v145</PlatformToolset>'
W '    <CharacterSet>NotSet</CharacterSet>'
W '    <UseDebugLibraries Condition="''$(Configuration)''==''Debug''">true</UseDebugLibraries>'
W '    <UseDebugLibraries Condition="''$(Configuration)''==''Release''">false</UseDebugLibraries>'
W '    <WholeProgramOptimization>false</WholeProgramOptimization>'
W '  </PropertyGroup>'
W '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.props" />'
W '  <ImportGroup Label="PropertySheets">'
W '    <Import Project="..\..\SE1SDK.props" />'
W '  </ImportGroup>'
W '  <PropertyGroup>'
W '    <CPDir>$(SolutionDir)ThirdParty\ClassicsPatch\</CPDir>'
W '    <TargetName>Entities_Custom</TargetName>'
W '    <OutDir>$(SolutionDir)Build\$(Configuration)\ClassicsPatch\</OutDir>'
W '    <IntDir>$(SolutionDir)Build\Obj\$(Configuration)\$(ProjectName)\</IntDir>'
W '    <LinkIncremental>false</LinkIncremental>'
W '  </PropertyGroup>'
W '  <ItemDefinitionGroup>'
W '    <ClCompile>'
W '      <AdditionalIncludeDirectories>$(ProjectDir);$(ProjectDir)..;$(CPDir)CustomMod;$(CPDir);$(SE1EngineIncludes);%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>'
W '      <PreprocessorDefinitions>$(SE1Preproc);%(PreprocessorDefinitions)</PreprocessorDefinitions>'
W '      <PrecompiledHeader>Use</PrecompiledHeader>'
W '      <PrecompiledHeaderFile>StdH.h</PrecompiledHeaderFile>'
W '      <WarningLevel>Level3</WarningLevel>'
W '      <DisableSpecificWarnings>$(SE1DisabledWarnings);%(DisableSpecificWarnings)</DisableSpecificWarnings>'
W '      <AdditionalOptions>$(SE1CompilerOptions) %(AdditionalOptions)</AdditionalOptions>'
W '      <ConformanceMode>false</ConformanceMode>'
W '      <EnableEnhancedInstructionSet>NoExtensions</EnableEnhancedInstructionSet>'
W '      <FloatingPointModel>Precise</FloatingPointModel>'
W '      <ExceptionHandling>Sync</ExceptionHandling>'
W '      <BufferSecurityCheck>false</BufferSecurityCheck>'
W '      <MultiProcessorCompilation>true</MultiProcessorCompilation>'
W '      <RuntimeTypeInfo>true</RuntimeTypeInfo>'
W '    </ClCompile>'
W '    <Link>'
W '      <SubSystem>Windows</SubSystem>'
W '      <AdditionalLibraryDirectories>$(SE1EngineLibraries);$(IntDir);%(AdditionalLibraryDirectories)</AdditionalLibraryDirectories>'
W '      <AdditionalDependencies>Engine.lib;ClassicsCore.lib;Ws2_32.lib;%(AdditionalDependencies)</AdditionalDependencies>'
W '      <GenerateDebugInformation>true</GenerateDebugInformation>'
W '      <GenerateMapFile>true</GenerateMapFile>'
W '      <ImageHasSafeExceptionHandlers>false</ImageHasSafeExceptionHandlers>'
W '      <RandomizedBaseAddress>false</RandomizedBaseAddress>'
W '      <BaseAddress>0x60310000</BaseAddress>'
W '    </Link>'
W '    <PreBuildEvent>'
W '      <Message>Import library for ClassicsCore.dll</Message>'
W '      <Command>lib.exe /nologo /machine:x86 /def:"$(ProjectDir)..\ClassicsCore.def" /out:"$(IntDir)ClassicsCore.lib"</Command>'
W '    </PreBuildEvent>'
W '  </ItemDefinitionGroup>'
W '  <ItemDefinitionGroup Condition="''$(Configuration)''==''Debug''">'
W '    <ClCompile>'
W '      <Optimization>Disabled</Optimization>'
W '      <RuntimeLibrary>MultiThreadedDebug</RuntimeLibrary>'
W '      <PreprocessorDefinitions>_DEBUG;%(PreprocessorDefinitions)</PreprocessorDefinitions>'
W '    </ClCompile>'
W '  </ItemDefinitionGroup>'
W '  <ItemDefinitionGroup Condition="''$(Configuration)''==''Release''">'
W '    <ClCompile>'
W '      <Optimization>MaxSpeed</Optimization>'
W '      <InlineFunctionExpansion>OnlyExplicitInline</InlineFunctionExpansion>'
W '      <IntrinsicFunctions>true</IntrinsicFunctions>'
W '      <OmitFramePointers>false</OmitFramePointers>'
W '      <StringPooling>true</StringPooling>'
W '      <RuntimeLibrary>MultiThreaded</RuntimeLibrary>'
W '      <PreprocessorDefinitions>NDEBUG;%(PreprocessorDefinitions)</PreprocessorDefinitions>'
W '    </ClCompile>'
W '    <Link>'
W '      <OptimizeReferences>true</OptimizeReferences>'
W '    </Link>'
W '  </ItemDefinitionGroup>'

# entity sources -> Ecc (run from Sources\ClassicsPatch, like the patch's own "cd CustomMod && ecc EntitiesTSE\...")
W '  <ItemGroup>'
foreach ($es in $esFiles) {
  $base = $es.Substring(0, $es.Length - 3)
  W "    <CustomBuild Include=`"$es`">"
  W "      <Message>Ecc $es</Message>"
  W "      <Command>cd /d `"`$(ProjectDir)..`" &amp;&amp; `"`$(SE1Ecc)`" `"EntitiesTSE\$es`"</Command>"
  W "      <Outputs>`$(ProjectDir)$base.cpp;`$(ProjectDir)$base.h;`$(ProjectDir)$($base)_tables.h</Outputs>"
  W '    </CustomBuild>'
}
W '  </ItemGroup>'

# compiled sources
W '  <ItemGroup>'
W '    <ClCompile Include="LibMain.cpp"><PrecompiledHeader>Create</PrecompiledHeader></ClCompile>'
foreach ($c in $handCpp) { W "    <ClCompile Include=`"$c`" />" }
W "    <ClCompile Include=`"..\..\EntitiesMP\Compat\HeapCompat.cpp`"><PrecompiledHeader>NotUsing</PrecompiledHeader></ClCompile>"
foreach ($es in $esFiles) { W "    <ClCompile Include=`"$($es.Substring(0, $es.Length - 3)).cpp`" />" }
W '  </ItemGroup>'
W '  <ItemGroup>'
W '    <None Include="..\ClassicsCore.def" />'
W '  </ItemGroup>'
W '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.targets" />'
W '</Project>'

$projPath = Join-Path $projDir 'EntitiesCP.vcxproj'
[IO.File]::WriteAllText($projPath, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))

# filters: mirror the folder structure of the entity sources
$sf = New-Object System.Text.StringBuilder
function F([string]$s) { [void]$sf.AppendLine($s) }
$folders = @($esFiles | ForEach-Object { Split-Path $_ } | Where-Object { $_ } | Sort-Object -Unique)
F '<?xml version="1.0" encoding="utf-8"?>'
F '<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
F '  <ItemGroup>'
foreach ($n in @('Entity Sources', 'Generated', 'Common') + ($folders | ForEach-Object { "Entity Sources\$_"; "Generated\$_" })) {
  F "    <Filter Include=`"$n`"><UniqueIdentifier>{$([guid]::NewGuid())}</UniqueIdentifier></Filter>"
}
F '  </ItemGroup>'
F '  <ItemGroup>'
foreach ($es in $esFiles) { $d = Split-Path $es; F "    <CustomBuild Include=`"$es`"><Filter>Entity Sources$(if ($d) { "\$d" })</Filter></CustomBuild>" }
F '  </ItemGroup>'
F '  <ItemGroup>'
foreach ($c in $handCpp) { F "    <ClCompile Include=`"$c`"><Filter>Common</Filter></ClCompile>" }
foreach ($es in $esFiles) { $d = Split-Path $es; F "    <ClCompile Include=`"$($es.Substring(0, $es.Length - 3)).cpp`"><Filter>Generated$(if ($d) { "\$d" })</Filter></ClCompile>" }
F '  </ItemGroup>'
F '</Project>'
[IO.File]::WriteAllText("$projPath.filters", $sf.ToString(), (New-Object Text.UTF8Encoding($false)))

Write-Host "Generated $projPath ($($esFiles.Count) entity sources)"
