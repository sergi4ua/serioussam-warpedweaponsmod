<#
  Regenerates Sources\EntitiesMP\EntitiesWW.vcxproj (+ .filters) from the files
  that are present in Sources\EntitiesMP. Run it after adding or removing an
  entity source (*.es) or a helper source (*.cpp in Common\ or Compat\).
#>
param()

$ErrorActionPreference = 'Stop'
$root    = Split-Path -Parent $PSScriptRoot
$projDir = Join-Path $root 'Sources\EntitiesMP'

$esFiles     = Get-ChildItem $projDir -Filter *.es | Sort-Object Name | ForEach-Object Name
# Entity sources that are not part of the retail 1.07 EntitiesMP.dll (unfinished/legacy classes).
# They still go through Ecc because other sources include their generated headers.
$notCompiled = @('AirWave','Catman','Cyborg','CyborgBike','Dragonman','Fishman','GhostBusterRay','Huanman',
                 'Mamut','Mamutman','Mantaman','Pipebomb','RobotDriving','RobotFixed','RobotFlying')
$commonCpp   = Get-ChildItem (Join-Path $projDir 'Common') -Filter *.cpp | Where-Object Name -ne 'Stats.cpp' | Sort-Object Name | ForEach-Object { "Common\$($_.Name)" }
$compatCpp   = Get-ChildItem (Join-Path $projDir 'Compat') -Filter *.cpp | Sort-Object Name | ForEach-Object { "Compat\$($_.Name)" }
$headers     = @(Get-ChildItem (Join-Path $projDir 'Common') -Filter *.h | ForEach-Object { "Common\$($_.Name)" }) +
               @(Get-ChildItem (Join-Path $projDir 'StdH') -Filter *.h | ForEach-Object { "StdH\$($_.Name)" })

$sb = New-Object System.Text.StringBuilder
function W([string]$s) { [void]$sb.AppendLine($s) }

W '<?xml version="1.0" encoding="utf-8"?>'
W '<!-- Generated by Tools\Generate-Project.ps1 - do not edit by hand. -->'
W '<Project DefaultTargets="Build" ToolsVersion="Current" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
W '  <ItemGroup Label="ProjectConfigurations">'
foreach ($cfg in 'Debug','Release') {
  W "    <ProjectConfiguration Include=`"$cfg|Win32`"><Configuration>$cfg</Configuration><Platform>Win32</Platform></ProjectConfiguration>"
}
W '  </ItemGroup>'
W '  <PropertyGroup Label="Globals">'
W '    <ProjectGuid>{6E3B2B6C-7A42-4C1D-9C51-57A2D0B1E5F1}</ProjectGuid>'
W '    <RootNamespace>EntitiesWW</RootNamespace>'
W '    <ProjectName>EntitiesWW</ProjectName>'
W '  </PropertyGroup>'
W '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.Default.props" />'
W '  <PropertyGroup Label="Configuration">'
W '    <ConfigurationType>DynamicLibrary</ConfigurationType>'
W '    <PlatformToolset Condition="''$(PlatformToolset)''==''''">v145</PlatformToolset>'
W '    <CharacterSet>NotSet</CharacterSet>'
W '    <UseDebugLibraries Condition="''$(Configuration)''==''Debug''">true</UseDebugLibraries>'
W '    <UseDebugLibraries Condition="''$(Configuration)''==''Release''">false</UseDebugLibraries>'
W '    <WholeProgramOptimization>false</WholeProgramOptimization>'
W '  </PropertyGroup>'
W '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.props" />'
W '  <ImportGroup Label="PropertySheets">'
W '    <Import Project="..\SE1SDK.props" />'
W '  </ImportGroup>'
W '  <PropertyGroup>'
W '    <TargetName>Entities$(ModExt)</TargetName>'
W '    <OutDir>$(SolutionDir)Build\$(Configuration)\</OutDir>'
W '    <IntDir>$(SolutionDir)Build\Obj\$(Configuration)\$(ProjectName)\</IntDir>'
W '    <LinkIncremental>false</LinkIncremental>'
W '  </PropertyGroup>'
W '  <ItemDefinitionGroup>'
W '    <ClCompile>'
W '      <AdditionalIncludeDirectories>$(ProjectDir);$(ProjectDir)StdH;$(ProjectDir)..;$(SE1EngineIncludes);%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>'
W '      <PreprocessorDefinitions>$(SE1Preproc);%(PreprocessorDefinitions)</PreprocessorDefinitions>'
W '      <PrecompiledHeader>Use</PrecompiledHeader>'
W '      <PrecompiledHeaderFile>StdH.h</PrecompiledHeaderFile>'
W '      <WarningLevel>Level3</WarningLevel>'
W '      <DisableSpecificWarnings>$(SE1DisabledWarnings);%(DisableSpecificWarnings)</DisableSpecificWarnings>'
W '      <AdditionalOptions>$(SE1CompilerOptions) %(AdditionalOptions)</AdditionalOptions>'
W '      <ConformanceMode>false</ConformanceMode>'
W '      <EnableEnhancedInstructionSet>NoExtensions</EnableEnhancedInstructionSet>'
W '      <FloatingPointModel>Precise</FloatingPointModel>'
W '      <ExceptionHandling>Sync</ExceptionHandling>'
W '      <BufferSecurityCheck>false</BufferSecurityCheck>'
W '      <MultiProcessorCompilation>true</MultiProcessorCompilation>'
W '      <RuntimeTypeInfo>true</RuntimeTypeInfo>'
W '    </ClCompile>'
W '    <Link>'
W '      <SubSystem>Windows</SubSystem>'
W '      <AdditionalLibraryDirectories>$(SE1EngineLibraries);%(AdditionalLibraryDirectories)</AdditionalLibraryDirectories>'
W '      <AdditionalDependencies>Engine.lib;%(AdditionalDependencies)</AdditionalDependencies>'
W '      <GenerateDebugInformation>true</GenerateDebugInformation>'
W '      <GenerateMapFile>true</GenerateMapFile>'
W '      <ImageHasSafeExceptionHandlers>false</ImageHasSafeExceptionHandlers>'
W '      <RandomizedBaseAddress>false</RandomizedBaseAddress>'
W '      <BaseAddress>0x60310000</BaseAddress>'
W '    </Link>'
W '  </ItemDefinitionGroup>'
W '  <ItemDefinitionGroup Condition="''$(Configuration)''==''Debug''">'
W '    <ClCompile>'
W '      <Optimization>Disabled</Optimization>'
W '      <RuntimeLibrary>MultiThreadedDebug</RuntimeLibrary>'
W '      <PreprocessorDefinitions>_DEBUG;%(PreprocessorDefinitions)</PreprocessorDefinitions>'
W '    </ClCompile>'
W '  </ItemDefinitionGroup>'
W '  <ItemDefinitionGroup Condition="''$(Configuration)''==''Release''">'
W '    <ClCompile>'
W '      <Optimization>MaxSpeed</Optimization>'
W '      <InlineFunctionExpansion>OnlyExplicitInline</InlineFunctionExpansion>'
W '      <IntrinsicFunctions>true</IntrinsicFunctions>'
W '      <OmitFramePointers>false</OmitFramePointers>'
W '      <StringPooling>true</StringPooling>'
W '      <RuntimeLibrary>MultiThreaded</RuntimeLibrary>'
W '      <PreprocessorDefinitions>NDEBUG;%(PreprocessorDefinitions)</PreprocessorDefinitions>'
W '    </ClCompile>'
W '    <Link>'
W '      <OptimizeReferences>true</OptimizeReferences>'
W '    </Link>'
W '  </ItemDefinitionGroup>'

# entity sources -> Ecc
W '  <ItemGroup>'
foreach ($es in $esFiles) {
  $name = [IO.Path]::GetFileNameWithoutExtension($es)
  W "    <CustomBuild Include=`"$es`">"
  W "      <Message>Ecc $es</Message>"
  W "      <Command>cd /d `"`$(ProjectDir)..`" &amp;&amp; `"`$(SE1Ecc)`" `"EntitiesMP/$es`"</Command>"
  W "      <Outputs>`$(ProjectDir)$name.cpp;`$(ProjectDir)$name.h;`$(ProjectDir)$($name)_tables.h</Outputs>"
  W '    </CustomBuild>'
}
W '  </ItemGroup>'

# compiled sources
W '  <ItemGroup>'
W '    <ClCompile Include="StdH\StdH.cpp"><PrecompiledHeader>Create</PrecompiledHeader></ClCompile>'
foreach ($c in $commonCpp) { W "    <ClCompile Include=`"$c`" />" }
foreach ($c in $compatCpp) { W "    <ClCompile Include=`"$c`"><PrecompiledHeader>NotUsing</PrecompiledHeader></ClCompile>" }
foreach ($es in $esFiles) {
  $name = [IO.Path]::GetFileNameWithoutExtension($es)
  if ($notCompiled -contains $name) { continue }
  W "    <ClCompile Include=`"$name.cpp`" />"
}
W '  </ItemGroup>'
W '  <ItemGroup>'
foreach ($h in $headers) { W "    <ClInclude Include=`"$h`" />" }
W '  </ItemGroup>'
W '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.targets" />'
W '</Project>'

$projPath = Join-Path $projDir 'EntitiesWW.vcxproj'
[IO.File]::WriteAllText($projPath, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))

# filters (just to keep the IDE tidy)
$sf = New-Object System.Text.StringBuilder
function F([string]$s) { [void]$sf.AppendLine($s) }
F '<?xml version="1.0" encoding="utf-8"?>'
F '<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
F '  <ItemGroup>'
foreach ($n in 'Entity Sources','Generated','Common','Compat','StdH') {
  F "    <Filter Include=`"$n`"><UniqueIdentifier>{$([guid]::NewGuid())}</UniqueIdentifier></Filter>"
}
F '  </ItemGroup>'
F '  <ItemGroup>'
foreach ($es in $esFiles) { F "    <CustomBuild Include=`"$es`"><Filter>Entity Sources</Filter></CustomBuild>" }
F '  </ItemGroup>'
F '  <ItemGroup>'
F '    <ClCompile Include="StdH\StdH.cpp"><Filter>StdH</Filter></ClCompile>'
foreach ($c in $commonCpp) { F "    <ClCompile Include=`"$c`"><Filter>Common</Filter></ClCompile>" }
foreach ($c in $compatCpp) { F "    <ClCompile Include=`"$c`"><Filter>Compat</Filter></ClCompile>" }
foreach ($es in $esFiles) {
  $name = [IO.Path]::GetFileNameWithoutExtension($es)
  if ($notCompiled -contains $name) { continue }
  F "    <ClCompile Include=`"$name.cpp`"><Filter>Generated</Filter></ClCompile>"
}
F '  </ItemGroup>'
F '</Project>'
[IO.File]::WriteAllText("$projPath.filters", $sf.ToString(), (New-Object Text.UTF8Encoding($false)))

Write-Host "Generated $projPath ($($esFiles.Count) entity sources)"
